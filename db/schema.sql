-- SubGuard BLD-03 initial PostgreSQL schema.
-- EVALUATION_RUN is intentionally standalone for the offline evaluator.

CREATE TABLE business (
    business_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    website_url TEXT NOT NULL,
    service_category TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE flow (
    flow_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES business (business_id) ON DELETE CASCADE,
    flow_type TEXT NOT NULL CHECK (flow_type IN ('sign-up', 'cancellation')),
    start_url TEXT NOT NULL,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE screen (
    screen_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flow_id BIGINT NOT NULL REFERENCES flow (flow_id) ON DELETE CASCADE,
    screen_order INTEGER NOT NULL CHECK (screen_order > 0),
    url TEXT NOT NULL,
    dom_path TEXT NOT NULL,
    visible_text_path TEXT NOT NULL,
    screenshot_path TEXT NOT NULL,
    UNIQUE (flow_id, screen_order)
);

CREATE TABLE interface_element (
    interface_element_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screen_id BIGINT NOT NULL REFERENCES screen (screen_id) ON DELETE CASCADE,
    selector_xpath TEXT,
    tag_name TEXT NOT NULL,
    text_content TEXT,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE requirement (
    requirement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requirement_code TEXT NOT NULL UNIQUE,
    tier TEXT NOT NULL CHECK (tier IN ('tier-1', 'tier-2')),
    act_section TEXT NOT NULL,
    question_text TEXT NOT NULL
);

CREATE TABLE clause (
    clause_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requirement_id BIGINT NOT NULL REFERENCES requirement (requirement_id) ON DELETE CASCADE,
    source_name TEXT NOT NULL,
    section_reference TEXT NOT NULL,
    clause_text TEXT NOT NULL,
    embedding_vec DOUBLE PRECISION[]
);

CREATE TABLE pipeline_run (
    run_id UUID PRIMARY KEY,
    model VARCHAR NOT NULL,
    screenshots_on BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE finding (
    finding_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL REFERENCES pipeline_run (run_id),
    flow_id BIGINT NOT NULL REFERENCES flow (flow_id) ON DELETE CASCADE,
    requirement_id BIGINT NOT NULL REFERENCES requirement (requirement_id) ON DELETE CASCADE,
    interface_element_id BIGINT REFERENCES interface_element (interface_element_id)
        ON DELETE SET NULL,
    verdict TEXT NOT NULL CHECK (verdict IN ('MET', 'NOT_MET', 'PARTIAL')),
    confidence_score NUMERIC(5, 4) CHECK (
        confidence_score IS NULL OR confidence_score BETWEEN 0 AND 1
    ),
    remediation_text TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (run_id, flow_id, requirement_id)
);

CREATE TABLE annotator (
    annotator_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE
);

CREATE TABLE annotation (
    annotation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flow_id BIGINT NOT NULL REFERENCES flow (flow_id) ON DELETE CASCADE,
    req_id BIGINT NOT NULL REFERENCES requirement (requirement_id) ON DELETE CASCADE,
    annotator_id BIGINT NOT NULL REFERENCES annotator (annotator_id) ON DELETE CASCADE,
    label TEXT NOT NULL CHECK (label IN ('MET', 'NOT_MET', 'PARTIAL', 'N/A', 'NC')),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (flow_id, req_id, annotator_id)
);

CREATE TABLE evaluation_run (
    evaluation_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_name TEXT NOT NULL,
    metrics JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX finding_flow_id_idx ON finding (flow_id);
CREATE INDEX finding_requirement_id_idx ON finding (requirement_id);
CREATE INDEX clause_requirement_id_idx ON clause (requirement_id);
